#!/usr/bin/env python3
"""Write the rules of this repo as one file for Codex: <CODEX_HOME>/AGENTS.md.

Claude Code follows the "@file" import lines in AGENTS.md. The Codex docs do not
name such lines, and a test with Codex CLI showed them as plain text. This script
writes one file that has the text of each imported file in place of its import
line. The always-on skills follow AGENTS.md, as in ~/.claude/CLAUDE.md.
Claude-only rule files (rules/subagent-routing.md) are not in the file.

Codex reads <CODEX_HOME>/AGENTS.override.md first. It reads AGENTS.md only when
the override file is missing or empty. CODEX_HOME is ~/.codex when it is not set.
Codex stops adding guidance files when their combined size reaches
project_doc_max_bytes (32 KiB by default).
Source: https://learn.chatgpt.com/docs/agent-configuration/agents-md

Usage:
  codex_rules.py --install [SKILL ...]  Write <CODEX_HOME>/AGENTS.md.
                                        Do nothing when the folder does not exist.
  codex_rules.py --check [SKILL ...]    Compare the file with the text that --install
                                        writes. Change nothing. Exit 1 on a difference.
  codex_rules.py --print [SKILL ...]    Print the text.
  codex_rules.py --refresh              Write the file again with the skills that its
                                        first line names, only when this repo folder
                                        wrote it. term_profile.py runs this after it
                                        writes the profile.

SKILL is the name of a skill folder in skills/, for example adhd-tr.

The first line of the written file names this repo folder and the skills. The
script replaces a file that is empty or has such a first line. It keeps any other
file: it prints a warning and changes nothing.
"""

import os
import re
import sys

REPO_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
AGENTS_FILE = os.path.join(REPO_DIR, "AGENTS.md")
MAX_DEPTH = 5             # Claude Code follows imports up to five levels deep.
SIZE_LIMIT = 32 * 1024    # Codex project_doc_max_bytes default.

IMPORT_LINE = re.compile(r"^@(\S+)\s*$")
FENCE = re.compile(r"^\s*(```|~~~)")
FRONTMATTER = re.compile(r"\A---\n.*?\n---\n", re.S)
MARKER = re.compile(r"^<!-- Generated by ai_agent_rules: (.+?) skills=([A-Za-z0-9_.,-]*)\. ")
SKILL_NAME = re.compile(r"^[A-Za-z0-9_.-]+$")


def codex_home():
    return os.environ.get("CODEX_HOME") or os.path.expanduser("~/.codex")


def read_text(path):
    with open(path, encoding="utf-8") as handle:
        return handle.read()


def resolve(target, base_dir):
    if target.startswith("~/"):
        return os.path.expanduser(target)
    if os.path.isabs(target):
        return target
    return os.path.normpath(os.path.join(base_dir, target))


def expand(path, depth=0):
    """Return the text of path with each import line replaced by the text of its file.

    Import lines inside a code block stay as they are.
    """
    out = []
    in_fence = False
    for line in read_text(path).split("\n"):
        if FENCE.match(line):
            in_fence = not in_fence
            out.append(line)
            continue
        match = None if in_fence else IMPORT_LINE.match(line)
        if not match or depth >= MAX_DEPTH:
            out.append(line)
            continue
        target = resolve(match.group(1), os.path.dirname(path))
        if os.path.isfile(target):
            out.append(expand(target, depth + 1).rstrip("\n"))
        else:
            out.append("<!-- %s: not found on this machine -->" % match.group(1))
    return "\n".join(out)


def marker_line(skills):
    return ("<!-- Generated by ai_agent_rules: %s skills=%s. Do not edit this file. "
            "Run install.sh in that folder to update it. -->" % (REPO_DIR, ",".join(skills)))


def render(skills):
    """Return the text of the Codex rules file."""
    parts = [marker_line(skills), expand(AGENTS_FILE).rstrip("\n")]
    for skill in skills:
        path = os.path.join(REPO_DIR, "skills", skill, "SKILL.md")
        parts.append(FRONTMATTER.sub("", read_text(path), count=1).strip("\n"))
    return "\n\n".join(parts) + "\n"


def file_state(path):
    """Return (state, marker match). state: missing, empty, ours or foreign."""
    try:
        text = read_text(path)
    except FileNotFoundError:
        return "missing", None
    if not text.strip():
        return "empty", None
    match = MARKER.match(text)
    return ("ours", match) if match else ("foreign", None)


def write_file(path, text):
    temp = path + ".tmp"
    with open(temp, "w", encoding="utf-8") as handle:
        handle.write(text)
    os.chmod(temp, 0o644)
    os.replace(temp, path)


def notes(home, text):
    """Print the warnings that do not change the result."""
    override = os.path.join(home, "AGENTS.override.md")
    try:
        if read_text(override).strip():
            print("  WARNING   %s is not empty. Codex reads it instead of AGENTS.md." % override)
    except OSError:
        pass
    size = len(text.encode("utf-8"))
    if size > SIZE_LIMIT:
        print("  WARNING   the file has %d bytes. Codex reads at most %d bytes of guidance by default"
              " (project_doc_max_bytes)." % (size, SIZE_LIMIT))


def check_skills(skills):
    for skill in skills:
        if not SKILL_NAME.match(skill) or not os.path.isfile(os.path.join(REPO_DIR, "skills", skill, "SKILL.md")):
            print("codex_rules.py: no skill %r in %s/skills" % (skill, REPO_DIR), file=sys.stderr)
            return False
    return True


def install(skills):
    home = codex_home()
    print("Codex rules: %s" % home)
    if not os.path.isdir(home):
        print("  skipped   the folder does not exist. Codex is not set up for this user.")
        return 0
    target = os.path.join(home, "AGENTS.md")
    state, _ = file_state(target)
    text = render(skills)
    if state == "foreign":
        print("  WARNING   AGENTS.md was not written by this repo. It is kept. To use the repo rules,")
        print("            move it away and run install.sh again.")
        return 0
    if state == "ours" and read_text(target) == text:
        print("  same      AGENTS.md")
    else:
        write_file(target, text)
        print("  written   AGENTS.md (%d bytes, from AGENTS.md and the skills %s)"
              % (len(text.encode("utf-8")), ", ".join(skills) or "-"))
    notes(home, text)
    return 0


def check(skills):
    home = codex_home()
    print("Codex rules: %s" % home)
    if not os.path.isdir(home):
        print("  skipped   the folder does not exist")
        return 0
    target = os.path.join(home, "AGENTS.md")
    state, _ = file_state(target)
    text = render(skills)
    result = 0
    if state in ("missing", "empty"):
        print("  missing   AGENTS.md (install.sh writes it)")
        result = 1
    elif state == "foreign":
        print("  WARNING   AGENTS.md was not written by this repo. install.sh keeps it.")
    elif read_text(target) != text:
        print("  outdated  AGENTS.md (install.sh writes it again)")
        result = 1
    else:
        print("  ok        AGENTS.md")
    notes(home, text)
    return result


def refresh():
    """Write the file again when this repo folder wrote it. Print nothing."""
    target = os.path.join(codex_home(), "AGENTS.md")
    state, match = file_state(target)
    if state != "ours" or match.group(1) != REPO_DIR:
        return 0
    skills = [skill for skill in match.group(2).split(",") if skill]
    if not check_skills(skills):
        return 1
    text = render(skills)
    if read_text(target) != text:
        write_file(target, text)
    return 0


def main(argv):
    if not argv or argv[0] not in ("--install", "--check", "--print", "--refresh"):
        print(__doc__.strip().split("\n\n")[-3], file=sys.stderr)
        print("usage: codex_rules.py --install|--check|--print [SKILL ...] | --refresh", file=sys.stderr)
        return 2
    mode, skills = argv[0], argv[1:]
    if mode == "--refresh":
        return refresh() if not skills else 2
    if not check_skills(skills):
        return 2
    if mode == "--print":
        sys.stdout.write(render(skills))
        return 0
    return install(skills) if mode == "--install" else check(skills)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
