#!/usr/bin/env python3
"""Tests for scripts/codex_rules.py.

Each test copies the script to a temporary repo with a small AGENTS.md and one
skill. CODEX_HOME points into the temporary folder, so the tests never touch
your real Codex folder.

Run: python3 -m unittest discover -s scripts/tests -p 'test_*.py'
"""

import os
import shutil
import subprocess
import sys
import tempfile
import unittest

SCRIPT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "codex_rules.py")

AGENTS = """# Rules

@local/ben.md

Text between imports.

```
@not/an/import.md
```

@local/override.md
@generated/missing.md
"""


class CodexRulesTest(unittest.TestCase):
    def setUp(self):
        self.root = tempfile.mkdtemp(prefix="cr-test-")
        self.repo = os.path.join(self.root, "repo")
        with open(SCRIPT, encoding="utf-8") as handle:
            self.write("scripts/codex_rules.py", handle.read())
        self.write("AGENTS.md", AGENTS)
        self.write("local/ben.md", "- I am a DBA.\n")
        # A relative import path is relative to the file that has the import line.
        self.write("local/override.md", "Türkçe yaz: dosya\n@nested.md\n")
        self.write("local/nested.md", "nested text\n")
        self.write("skills/adhd-tr/SKILL.md", "---\nname: adhd-tr\ndescription: x\n---\n\n# adhd-tr\n\nShort answers.\n")
        self.codex = os.path.join(self.root, "codex")
        os.makedirs(self.codex)
        self.target = os.path.join(self.codex, "AGENTS.md")

    def tearDown(self):
        shutil.rmtree(self.root, ignore_errors=True)

    def write(self, relative, text):
        path = os.path.join(self.repo, relative)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as handle:
            handle.write(text)

    def run_script(self, *args, codex=None):
        env = dict(os.environ, CODEX_HOME=codex or self.codex)
        return subprocess.run([sys.executable, os.path.join(self.repo, "scripts", "codex_rules.py")] + list(args),
                              env=env, stdout=subprocess.PIPE, stderr=subprocess.PIPE, universal_newlines=True)

    def read_target(self):
        with open(self.target, encoding="utf-8") as handle:
            return handle.read()

    def test_print_inlines_imports_and_skill(self):
        result = self.run_script("--print", "adhd-tr")
        self.assertEqual(result.returncode, 0, result.stderr)
        text = result.stdout
        self.assertTrue(text.startswith("<!-- Generated by ai_agent_rules: %s skills=adhd-tr. " % self.repo), text[:200])
        self.assertIn("- I am a DBA.", text)
        self.assertIn("Türkçe yaz: dosya\nnested text", text)
        self.assertNotIn("@local/ben.md", text)
        self.assertIn("```\n@not/an/import.md\n```", text)
        self.assertIn("<!-- generated/missing.md: not found on this machine -->", text)
        self.assertIn("# adhd-tr\n\nShort answers.", text)
        self.assertNotIn("name: adhd-tr", text)

    def test_local_override_import_missing_is_a_placeholder(self):
        os.remove(os.path.join(self.repo, "local", "override.md"))
        result = self.run_script("--print", "adhd-tr")
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn("<!-- local/override.md: not found on this machine -->", result.stdout)
        self.assertNotIn("@local/override.md", result.stdout)

    def test_install_check_and_second_install(self):
        self.assertEqual(self.run_script("--check", "adhd-tr").returncode, 1)
        result = self.run_script("--install", "adhd-tr")
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn("written   AGENTS.md", result.stdout)
        self.assertEqual(self.read_target(), self.run_script("--print", "adhd-tr").stdout)
        self.assertEqual(oct(os.stat(self.target).st_mode & 0o777), "0o644")
        check = self.run_script("--check", "adhd-tr")
        self.assertEqual(check.returncode, 0, check.stdout)
        self.assertIn("ok        AGENTS.md", check.stdout)
        self.assertIn("same      AGENTS.md", self.run_script("--install", "adhd-tr").stdout)

    def test_changed_rules_show_as_outdated(self):
        self.run_script("--install", "adhd-tr")
        self.write("AGENTS.md", AGENTS + "\nNew rule.\n")
        check = self.run_script("--check", "adhd-tr")
        self.assertEqual(check.returncode, 1)
        self.assertIn("outdated  AGENTS.md", check.stdout)

    def test_empty_file_is_replaced_and_foreign_file_is_kept(self):
        with open(self.target, "w", encoding="utf-8"):
            pass
        self.assertIn("written", self.run_script("--install", "adhd-tr").stdout)
        with open(self.target, "w", encoding="utf-8") as handle:
            handle.write("my own codex rules\n")
        result = self.run_script("--install", "adhd-tr")
        self.assertEqual(result.returncode, 0)
        self.assertIn("WARNING   AGENTS.md was not written by this repo", result.stdout)
        self.assertEqual(self.read_target(), "my own codex rules\n")
        self.assertEqual(self.run_script("--check", "adhd-tr").returncode, 0)

    def test_refresh_only_for_a_file_of_this_repo(self):
        self.run_script("--install", "adhd-tr")
        self.write("local/ben.md", "- I am a DBA and a developer.\n")
        self.assertEqual(self.run_script("--refresh").returncode, 0)
        self.assertIn("- I am a DBA and a developer.", self.read_target())
        other = self.read_target().replace(self.repo, os.path.join(self.root, "other-clone"), 1)
        with open(self.target, "w", encoding="utf-8") as handle:
            handle.write(other)
        self.write("local/ben.md", "- changed again\n")
        self.run_script("--refresh")
        self.assertEqual(self.read_target(), other)

    def test_missing_codex_folder_is_skipped(self):
        missing = os.path.join(self.root, "no-codex")
        result = self.run_script("--install", "adhd-tr", codex=missing)
        self.assertEqual(result.returncode, 0)
        self.assertIn("skipped", result.stdout)
        self.assertFalse(os.path.exists(missing))
        self.assertEqual(self.run_script("--check", "adhd-tr", codex=missing).returncode, 0)

    def test_override_file_warning_and_unknown_skill(self):
        with open(os.path.join(self.codex, "AGENTS.override.md"), "w", encoding="utf-8") as handle:
            handle.write("override\n")
        self.assertIn("Codex reads it instead of AGENTS.md", self.run_script("--install", "adhd-tr").stdout)
        result = self.run_script("--install", "no-such-skill")
        self.assertEqual(result.returncode, 2)
        self.assertIn("no skill", result.stderr)


if __name__ == "__main__":
    unittest.main()
